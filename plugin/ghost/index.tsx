// Ghost as a Vencord userplugin: injects the Ghost theme itself (one install),
// adds a settings UI for its --ghost-* variables, and takes the background
// (and, opt-in, the accent) from what's playing on Spotify (via Discord's
// Spotify connection).
//
//   index.tsx       plugin definition: start/stop
//   settings.tsx    settings (sections) → CSS variables / classes on <html>
//   player.ts       current Spotify track (Discord's SpotifyStore)
//   background.ts   cover blurred once into a canvas, crossfaded
//   accent.ts       accent colour picked from the cover
//   ghost.css       the theme, generated by build.mjs from theme/ (not in git)
//
// Lyrics (later): port spicetify-ghost/src/lyrics' providers and parsers into
// lyrics/ on top of player.ts (TrackInfo, position()).

import { disableStyle, enableStyle } from "@api/Styles";
import definePlugin from "@utils/types";

import { startAccent, stopAccent } from "./accent";
import { startBackground, stopBackground } from "./background";
import style from "./ghost.css?managed";
import { applySettings, clearSettings, settings } from "./settings";

export default definePlugin({
    name: "Ghost",
    description: "Glassy Ghost theme with a heavily blurred background from your Spotify album art. Includes the theme — no need to enable ghost.theme.css as well.",
    authors: [{ name: "RazerGhost", id: 0n }],
    tags: ["Appearance", "Customisation", "Media"],
    settings,

    start() {
        enableStyle(style);
        applySettings();
        startBackground();
        startAccent();
    },

    stop() {
        stopAccent();
        stopBackground();
        clearSettings();
        disableStyle(style);
    },
});
